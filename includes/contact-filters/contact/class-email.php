namespace QuillCRM\Contact_Filters\Contact;

use QuillCRM\Abstracts\Filter;

use QuillCRM\Models\Contact_Model;
use QuillCRM\Managers\Filters_Manager;

/**
 * Email class
 */
class Email extends Filter {

	/**
	 * Name
	 *
	 * @var string
	 *
	 * @since 1.0.0
	 */
	public $name = 'Email';

	/**
	 * Slug
	 *
	 * @var string
	 *
	 * @since 1.0.0
	 */
	public $slug = 'contact_email';

	/**
	 * Group
	 *
	 * @var string
	 *
	 * @since 1.0.0
	 */
	public $group = 'contact';

	/**
	 * Type
	 *
	 * @var string
	 *
	 * @since 1.0.0
	 */
	public $type = 'text';
}

Filters_Manager::instance()->register( new Email() );
